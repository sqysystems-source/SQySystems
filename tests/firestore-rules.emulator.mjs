// Run only through npm run test:rules. Never points at a production project.
import {readFileSync} from 'node:fs';
import {initializeTestEnvironment,assertSucceeds,assertFails} from '@firebase/rules-unit-testing';
import {doc,collection,getDoc,getDocs,setDoc,updateDoc,deleteDoc,serverTimestamp,Timestamp} from 'firebase/firestore';
if(!process.env.FIRESTORE_EMULATOR_HOST) throw new Error('Start the Firestore emulator with npm run test:rules.');
const [host,port]=process.env.FIRESTORE_EMULATOR_HOST.split(':');
if(!['127.0.0.1','localhost'].includes(host))throw new Error('Rules tests must use a local emulator.');
const env=await initializeTestEnvironment({projectId:'demo-sqysystems',firestore:{host,port:Number(port),rules:readFileSync(new URL('../firestore.rules',import.meta.url),'utf8')}});
const config={apiKey:'public-web-key',authDomain:'test-db-f6315.firebaseapp.com',projectId:'test-db-f6315',storageBucket:'test-db-f6315.firebasestorage.app',messagingSenderId:'123456',appId:'1:123456:web:abc123'};
const email='merchant@example.com';
const store=()=>({merchantEmail:email,storeName:'Store',storeApiBaseUrl:'https://store.example.com',plan:'Custom E-Shop',status:'active',firebaseConfig:config,updatedAt:serverTimestamp()});
const contact=()=>({name:'Prospect',email:'prospect@example.com',message:'I would like an e-shop.',createdAt:serverTimestamp(),uid:null,source:'website-contact-form'});
try{
 await env.clearFirestore();
 await env.withSecurityRulesDisabled(async ctx=>{
  const db=ctx.firestore();
  await setDoc(doc(db,'users/admin'),{uid:'admin',role:'superadmin',email:'owner@example.com'});
  await setDoc(doc(db,'users/legacyadmin'),{uid:'legacyadmin',role:'admin',email:'legacy@example.com'});
  await setDoc(doc(db,'users/client'),{uid:'client',role:'client',email:'client@example.com'});
 });
 const anon=env.unauthenticatedContext().firestore(),client=env.authenticatedContext('client').firestore(),admin=env.authenticatedContext('admin').firestore(),legacy=env.authenticatedContext('legacyadmin').firestore();
 await assertSucceeds(getDoc(doc(anon,'merchant_stores',email)));
 await assertFails(getDocs(collection(anon,'merchant_stores')));
 await assertFails(getDocs(collection(client,'merchant_stores')));
 await assertSucceeds(setDoc(doc(admin,'merchant_stores',email),store()));
 await assertSucceeds(getDoc(doc(anon,'merchant_stores',email)));
 await assertSucceeds(getDocs(collection(admin,'merchant_stores')));
 await assertSucceeds(getDocs(collection(legacy,'merchant_stores')));
 await assertFails(setDoc(doc(client,'merchant_stores',email),store()));
 await assertFails(setDoc(doc(admin,'merchant_stores',email),{...store(),private_key:'secret'}));
 await assertFails(setDoc(doc(admin,'merchant_stores',email),{...store(),firebaseConfig:{...config,private_key:'secret'}}));
 await assertFails(setDoc(doc(admin,'merchant_stores','wrong@example.com'),store()));
 await assertSucceeds(updateDoc(doc(admin,'merchant_stores',email),{status:'disabled',updatedAt:serverTimestamp()}));
 await assertSucceeds(updateDoc(doc(admin,'merchant_stores',email),{status:'deleted',updatedAt:serverTimestamp()}));
 await assertSucceeds(getDoc(doc(client,'users/client')));
 await assertFails(getDoc(doc(client,'users/admin')));
 await assertFails(getDocs(collection(client,'users')));
 await assertSucceeds(getDocs(collection(admin,'users')));
 await assertFails(updateDoc(doc(client,'users/client'),{role:'superadmin'}));
 await assertFails(updateDoc(doc(client,'users/client'),{tenantStore:store()}));
 await assertSucceeds(updateDoc(doc(client,'users/client'),{company:'Client company'}));
 const newUser=env.authenticatedContext('new-user').firestore();
 await assertFails(setDoc(doc(newUser,'users/new-user'),{uid:'new-user',role:'admin'}));
 await assertSucceeds(setDoc(doc(newUser,'users/new-user'),{uid:'new-user',role:'client'}));
 await assertSucceeds(setDoc(doc(anon,'messages/ticket'),contact()));
 await assertFails(setDoc(doc(anon,'messages/fake-read'),{...contact(),status:'read'}));
 await assertFails(getDoc(doc(anon,'messages/ticket')));
 await assertFails(getDocs(collection(client,'messages')));
 await assertSucceeds(getDocs(collection(admin,'messages')));
 await assertSucceeds(updateDoc(doc(admin,'messages/ticket'),{status:'read',updatedAt:serverTimestamp()}));
 await assertFails(updateDoc(doc(client,'messages/ticket'),{status:'resolved',updatedAt:serverTimestamp()}));
 await assertFails(updateDoc(doc(admin,'messages/ticket'),{message:'Edited body'}));
 await assertSucceeds(deleteDoc(doc(admin,'messages/ticket')));
 const paid={clientEmail:email,clientName:'Merchant',packageDetails:'Custom E-Shop + Viva Wallet',amountCents:70000,currency:'EUR',status:'paid',source:'manual',paidAt:Timestamp.fromDate(new Date('2026-10-15T12:00:00Z')),createdBy:'admin',createdAt:serverTimestamp(),updatedAt:serverTimestamp()};
 await assertFails(setDoc(doc(client,'client_payments/payment'),paid));
 await assertSucceeds(setDoc(doc(admin,'client_payments/payment'),paid));
 await assertFails(getDocs(collection(anon,'client_payments')));
 await assertSucceeds(getDocs(collection(admin,'client_payments')));
 await assertFails(setDoc(doc(admin,'client_payments/invalid'),{...paid,amountCents:'70000'}));
 console.log('Firestore emulator allow/deny and validation checks passed.');
}finally{await env.cleanup()}
